#!/usr/bin/env python3
"""Regenerates games/registry.js from every games/<slug>/game.json (the launcher loads it via <script src>).

Game PRs never edit registry.js: the gate rebuilds it on main after each merge, so parallel sessions can't
conflict on it. Usage: python3 tools/build_registry.py [--check]   (--check: exit 1 if the file is stale)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GAMES = ROOT / "games"
OUT = GAMES / "registry.js"
FIELDS = ("id", "slug", "title", "genre", "coreMechanic", "setting", "description", "controls", "createdAt", "accentColor")


def build() -> str:
    entries = []
    for manifest in sorted(GAMES.glob("*/game.json")):
        try:
            meta = json.loads(manifest.read_text(encoding="utf-8"))
        except ValueError:
            continue  # check_games.py reports invalid manifests
        entry = {k: meta[k] for k in FIELDS if k in meta}
        entry["path"] = f"./games/{manifest.parent.name}/index.html"
        entries.append(entry)
    entries.sort(key=lambda e: (str(e.get("id", "")), e["path"]))
    return ("// GENERATED by tools/build_registry.py from games/*/game.json. Do not edit by hand.\n"
            "window.ARCADE_REGISTRY = " + json.dumps(entries, indent=2, ensure_ascii=False) + ";\n")


def main() -> int:
    ap = argparse.ArgumentParser(description="Rebuild games/registry.js from game manifests.")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if args.check:
        if current != text:
            print("REGISTRY STALE: run python3 tools/build_registry.py")
            return 1
        print("REGISTRY OK")
        return 0
    if current != text:
        OUT.write_text(text, encoding="utf-8")
        print(f"REGISTRY UPDATED ({text.count(chr(10) + '  {')} game(s))")
    else:
        print("REGISTRY UNCHANGED")
    return 0


if __name__ == "__main__":
    sys.exit(main())
